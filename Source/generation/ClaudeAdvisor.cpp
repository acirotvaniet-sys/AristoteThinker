#include "ClaudeAdvisor.h"

namespace
{
    constexpr const char* endpoint = "https://api.anthropic.com/v1/messages";
    constexpr const char* model    = "claude-opus-5-5";

    juce::var obj (std::initializer_list<std::pair<const char*, juce::var>> props)
    {
        auto* o = new juce::DynamicObject();
        for (const auto& [k, v] : props)
            o->setProperty (k, v);
        return juce::var (o);
    }

    juce::String buildPrompt (const AnalysisResult& a, const std::vector<Preset>& presets)
    {
        juce::String s;
        s << "Analysis of the loop the producer just played:\n"
          << "- tempo: " << juce::String (a.bpm, 1) << " BPM\n"
          << "- key: " << a.keyName << "\n"
          << "- chords: " << a.chordProgressionText (8) << "\n"
          << "- darkness " << juce::String (a.darkness, 2) << ", brightness " << juce::String (a.brightness, 2)
          << ", energy " << juce::String (a.energy, 2) << ", density " << juce::String (a.density, 2) << " (0..1)\n\n"
          << "Rhythmic modulation presets generated by the rule engine:\n";

        for (const auto& p : presets)
            s << "- id " << p.id << " | pattern " << p.archetype << " | mood " << moodToString (p.mood)
              << " | " << juce::String (p.lengthBeats, 0) << " beats | current name \"" << p.name
              << "\" | notes: " << p.note << "\n";

        s << "\nFor each preset, give a new name (2 or 3 words, evocative of its mood and of Aristotle / "
             "ancient Greek philosophy, no quotes, no key name) and a one-sentence producer note "
             "(max 140 characters) explaining why this rhythm suits these chords in a trap beat.\n"
             "Answer with JSON only, no prose, exactly in this shape:\n"
             "{\"presets\":[{\"id\":\"...\",\"name\":\"...\",\"note\":\"...\"}]}";
        return s;
    }
}

juce::Result ClaudeAdvisor::request (const juce::String& apiKey,
                                     const AnalysisResult& analysis,
                                     const std::vector<Preset>& presets,
                                     std::vector<Suggestion>& out)
{
    if (apiKey.trim().isEmpty())
        return juce::Result::fail ("No API key");

    juce::Array<juce::var> messages;
    messages.add (obj ({ { "role", "user" }, { "content", buildPrompt (analysis, presets) } }));

    const auto body = obj ({
        { "model", model },
        { "max_tokens", 4000 },
        { "system", "You are a seasoned trap music producer who names presets for a rhythmic "
                    "modulation plugin themed around Aristotle. You answer with strict JSON only." },
        { "output_config", obj ({ { "effort", "low" } }) },
        { "fallbacks", "default" },            // repli côté serveur si le modèle refuse
        { "messages", juce::var (messages) }
    });

    const auto json = juce::JSON::toString (body, true);

    juce::String headers;
    headers << "Content-Type: application/json\r\n"
            << "x-api-key: " << apiKey.trim() << "\r\n"
            << "anthropic-version: 2026-10-21\r\n"
            << "anthropic-beta: server-side-fallback-2026-07-01\r\n";

    int status = 0;
    auto url = juce::URL (endpoint).withPOSTData (json);
    auto options = juce::URL::InputStreamOptions (juce::URL::ParameterHandling::inPostData)
                       .withExtraHeaders (headers)
                       .withConnectionTimeoutMs (30000)
                       .withStatusCode (&status)
                       .withHttpRequestCmd ("POST");

    auto stream = url.createInputStream (options);
    if (stream == nullptr)
        return juce::Result::fail ("Could not reach api.anthropic.com");

    const auto response = stream->readEntireStreamAsString();
    const auto parsed = juce::JSON::parse (response);

    if (status != 200)
    {
        auto msg = parsed.getProperty ("error", {}).getProperty ("message", {}).toString();
        return juce::Result::fail ("HTTP " + juce::String (status) + (msg.isNotEmpty() ? ": " + msg : juce::String()));
    }

    if (parsed.getProperty ("stop_reason", {}).toString() == "refusal")
        return juce::Result::fail ("Claude declined the request");

    juce::String text;
    if (auto* content = parsed.getProperty ("content", {}).getArray())
        for (const auto& block : *content)
            if (block.getProperty ("type", {}).toString() == "text")
                text << block.getProperty ("text", {}).toString();

    // Tolère d'éventuels ```json ... ``` autour de la réponse
    const int start = text.indexOfChar ('{');
    const int end = text.lastIndexOfChar ('}');
    if (start < 0 || end <= start)
        return juce::Result::fail ("Unexpected answer format");

    const auto answer = juce::JSON::parse (text.substring (start, end + 1));
    if (auto* list = answer.getProperty ("presets", {}).getArray())
    {
        for (const auto& item : *list)
        {
            Suggestion s;
            s.presetId = item.getProperty ("id", {}).toString();
            s.name = item.getProperty ("name", {}).toString().trim().substring (0, 40);
            s.note = item.getProperty ("note", {}).toString().trim().substring (0, 200);
            if (s.presetId.isNotEmpty() && s.name.isNotEmpty())
                out.push_back (s);
        }
    }

    return out.empty() ? juce::Result::fail ("No suggestions in answer") : juce::Result::ok();
}
